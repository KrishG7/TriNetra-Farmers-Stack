from pydantic import BaseModel, Field, field_validator, ConfigDict
from typing import Optional, List
from datetime import date

# -------------------------
# COMMON / BASE SCHEMAS
# -------------------------
class MessageResponse(BaseModel):
    message: str


# -------------------------
# AUTH / FARMER SCHEMAS
# ========================

class FarmerRegister(BaseModel):
    """
    Farmer registration request.
    Client sends these fields - farmer_id is auto-generated by server.
    """
    name: str = Field(..., min_length=1, examples=["Ramesh Kumar"])
    phone: str = Field(..., pattern=r"^\d{10}$", examples=["9876543210"])
    state: str = Field(..., examples=["Maharashtra"])
    district: str = Field(..., examples=["Pune"])
    language: str = Field(default="en", examples=["en"])
    
    @field_validator('name')
    @classmethod
    def name_no_numbers(cls, v: str) -> str:
        if any(char.isdigit() for char in v):
            raise ValueError('Name cannot contain numbers')
        return v.strip()


class FarmerResponse(BaseModel):
    """
    Farmer profile response.
    Includes the auto-generated farmer_id.
    """
    farmer_id: str = Field(..., examples=["FARM_9876543210_a1b2c3d4"])
    name: str = Field(..., examples=["Ramesh Kumar"])
    phone: str = Field(..., examples=["9876543210"])
    state: str = Field(..., examples=["Maharashtra"])
    district: str = Field(..., examples=["Pune"])
    language: Optional[str] = Field(default="en", examples=["en"])
    
    model_config = ConfigDict(from_attributes=True)


class LoginRequest(BaseModel):
    phone: str = Field(..., pattern=r"^\d{10}$")


class OTPVerify(BaseModel):
    phone: str = Field(..., pattern=r"^\d{10}$")
    otp: str = Field(..., min_length=4, max_length=6)


# -------------------------
# SOIL SCHEMAS
# -------------------------
class SoilRequest(BaseModel):
    district: str = Field(..., examples=["Pune"])
    nitrogen: float = Field(..., ge=0, examples=[45.0])
    phosphorus: float = Field(..., ge=0, examples=[30.0])
    potassium: float = Field(..., ge=0, examples=[40.0])
    ph: float = Field(..., ge=0, le=14, examples=[6.5])
    rainfall: float = Field(..., ge=0, examples=[120.0])
    lang: str = Field(default="en")  # Language code for translations


class SoilPredictionResponse(BaseModel):
    recommended_crop: str = Field(..., examples=["Wheat"])
    confidence: Optional[float] = Field(None, ge=0, le=1, examples=[0.87])
    explanation: Optional[str] = None


# -------------------------
# MARKET SCHEMAS
# -------------------------
class MarketQuery(BaseModel):
    crop_name: str = Field(..., examples=["Rice"])
    state: Optional[str] = Field(None, examples=["Punjab"])
    language: str = Field(default="en")


class MarketPriceResponse(BaseModel):
    crop_name: str
    state: str
    average_price: float
    last_updated: date


class MarketHistoryItem(BaseModel):
    date: date
    price: float


class MarketHistoryResponse(BaseModel):
    crop_name: str
    state: str
    history: List[MarketHistoryItem]


# -------------------------
# CREDIT / LOAN SCHEMAS
# -------------------------
class CreditRequest(BaseModel):
    farmer_id: str
    land_area_acres: float = Field(..., gt=0, examples=[2.5])
    crop_name: str = Field(..., examples=["Wheat"])
    expected_yield_quintal: float = Field(..., gt=0, examples=[25.0])


class CreditResponse(BaseModel):
    eligible_amount: float
    interest_rate: float
    repayment_period_months: int
    eligibility_status: str = Field(..., examples=["eligible"])


# -------------------------
# LOCATION SCHEMAS
# -------------------------
class Location(BaseModel):
    lat: float = Field(..., ge=-90, le=90)
    lng: float = Field(..., ge=-180, le=180)
    district: Optional[str] = None